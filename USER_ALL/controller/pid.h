#ifndef PID_H
#define PID_H
#include "struct_typedef.h"
#define MIN_AUTO 2.0f


enum PID_MODE
{
    PID_POSITION = 0,
    PID_DELTA
};

typedef struct
{
    uint8_t mode;
    //PID 三参数
    fp32 Kp;
    fp32 Ki;
    fp32 Kd;

    fp32 max_out;  //最大输出
    fp32 max_iout; //最大积分输出

    fp32 set;
    fp32 fdb;

    fp32 out;
    fp32 Pout;
    fp32 Iout;
    fp32 Dout;
    fp32 Dbuf[3];  //微分项 0最新 1上一次 2上上次
    fp32 error[3]; //误差项 0最新 1上一次 2上上次
	
	fp32 integral_valve;//积分阀门

} pid_type_def;

#define LimitMax(input, max)   \
    {                          \
        if (input > max)       \
        {                      \
            input = max;       \
        }                      \
        else if (input < -max) \
        {                      \
            input = -max;      \
        }                      \
    }
/**
  * @brief          pid struct data init
  * @param[out]     pid: PID struct data point
  * @param[in]      mode: PID_POSITION: normal pid
  *                 PID_DELTA: delta pid
  * @param[in]      PID: 0: kp, 1: ki, 2:kd
  * @param[in]      max_out: pid max out
  * @param[in]      max_iout: pid max iout
  * @retval         none
  */
/**
  * @brief          pid struct data init
  * @param[out]     pid: PID结构数据指针
  * @param[in]      mode: PID_POSITION:普通PID
  *                 PID_DELTA: 差分PID
  * @param[in]      PID: 0: kp, 1: ki, 2:kd
  * @param[in]      max_out: pid最大输出
  * @param[in]      max_iout: pid最大积分输出
  * @retval         none
  */
void PID_init(pid_type_def *pid, uint8_t mode, const fp32 PID[3], fp32 max_out, fp32 max_iout);

typedef struct {
    float kp;              // 比例系数
    float ki;              // 积分系数
    float kd;              // 微分系数

    float integral;        // 积分累加值
    float integral_max;    // 积分限幅（正负对称）
    float output_max;      // 输出限幅（正负对称）

    float prev_error;      // 上次误差（用于微分）
    float prev_measure;    // 上次测量值（用于微分先行，可选）

    uint8_t first_run;     // 首次运行标志（微分初值）
} PID_t;
extern PID_t pid_yaw;
void PID_Init(PID_t *pid, float kp, float ki, float kd,
              float integral_max, float output_max);
float PID_Calc(PID_t *pid, float target, float measure, float dt);
extern  float DM_PositionLoopPIDController(pid_type_def *pid, fp32 ref, fp32 set);

#endif
